"""Allowlisted, dependency-free public packaging and versioned offline shell."""
from pathlib import Path
import hashlib
import json
import shutil
import sys
ROOT = Path(__file__).resolve().parents[1]
def runtime_files():
    names = ['index.html', 'style.css', '.nojekyll', 'assets/icon.svg']
    for folder in ['js', 'vendor/vanillajs/modules', 'vendor/vanillajs/api', 'mods']:
        names.extend(str(p.relative_to(ROOT)) for p in (ROOT / folder).rglob('*') if p.is_file() and p.suffix in {'.js', '.json'})
    names.extend(['LICENSE', 'NOTICE', 'vendor/vanillajs/LICENSE', 'vendor/PROVENANCE.json'])
    return sorted(names)
def worker_source(names):
    identity = hashlib.sha256()
    for name in names:
        identity.update(name.encode() + b'\0' + (ROOT / name).read_bytes() + b'\0')
    version = identity.hexdigest()[:20]
    return """// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/build.py --write-sw. Entire effective runtime is hashed.
const PREFIX='outruin:'+new URL(self.registration.scope).pathname+':';
const CACHE=PREFIX+'%s';
const FILES=%s;
self.addEventListener('install',event=>event.waitUntil((async()=>{
  const cache=await caches.open(CACHE);
  await cache.addAll(FILES.map(file=>new URL(file,self.registration.scope).href));
  await self.skipWaiting();
})()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  const keys=await caches.keys();
  await Promise.all(keys.filter(k=>k.startsWith(PREFIX)&&k!==CACHE).map(k=>caches.delete(k)));
  await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url),scope=new URL(self.registration.scope);
  if(event.request.method!=='GET'||url.origin!==scope.origin||!url.pathname.startsWith(scope.pathname))return;
  const relative=url.pathname.slice(scope.pathname.length)||'index.html';
  const file=relative==='index.html'?'index.html':relative;
  if(!FILES.includes(file))return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE),key=new URL(file,scope).href;
    return (await cache.match(key))||fetch(event.request);
  })());
});
""" % (version, json.dumps(names, separators=(',', ':')))
def main():
    names = runtime_files()
    worker = worker_source(names)
    if '--write-sw' in sys.argv:
        (ROOT / 'sw.js').write_text(worker)
    elif not (ROOT / 'sw.js').exists() or (ROOT / 'sw.js').read_text() != worker:
        raise SystemExit('Offline manifest is stale. Run: python3 scripts/build.py --write-sw')
    out = ROOT / 'dist'
    if out.exists():
        shutil.rmtree(out)
    for name in names + ['sw.js']:
        target = out / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / name, target)
    print(f'Packaged {len(names)+1} files ({sum(p.stat().st_size for p in out.rglob("*") if p.is_file()):,} bytes)')
if __name__ == '__main__':
    main()
